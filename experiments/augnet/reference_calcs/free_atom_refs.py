#!/usr/bin/env python3
"""
free_atom_refs.py

Generate free-atom PAW occupancy references (rho_ij at atomic initialization)
consistent with Materials Project static calculations (MPStaticSet).

Strategy (one calculation per element, seconds each):
  - one atom in an orthorhombic box (unequal sides)
  - inputs generated by pymatgen's MPStaticSet -> MP's preferred POTCAR
    variant, MP INCAR defaults
  - overridden to a NON-SELF-CONSISTENT run:
        ICHARG = 12   (fixed atomic-superposition charge density)
        NELM   = 1    (single diagonalization, no density/occupancy update)
    so the augmentation occupancies written to CHGCAR are exactly the
    spherically-symmetric free-atom rho_ij in the projector basis of the
    dataset's POTCAR. Nothing is converged, so nothing can fail to converge.

DFT+U / LMAXMIX handling ("same exact treatment as Materials Project"):
  - A lone neutral atom never triggers MP's +U (MP applies U to selected
    d-elements only in the presence of O/F anions); this is verified at
    startup. With ICHARG=12 / NELM=1, U could not alter rho_ij anyway.
  - What DOES differ between MP CHGCARs is LMAXMIX, which truncates the
    one-center occupancies written to CHGCAR. MP convention (and the
    Koker et al. 2024 post-processing): LMAXMIX = 4 if any LDAUL uses l=2,
    6 if any uses l=3, applied ONLY when LDAU = .TRUE.; default otherwise.
  - Therefore, for every element in MP's U table we emit a SECOND reference
    run ("ldau_convention/") that only differs by LMAXMIX (per the rule
    above), so you have references matching both the U-active and U-inactive
    CHGCAR truncations found in MP data. The occupancy VALUES are identical
    by construction; only the truncation of what is written differs.
  - At startup the script asserts that the installed pymatgen MPStaticSet
    still reproduces MP's +U configuration (LDAUTYPE=2, the MP U values,
    the O/F anion trigger) and aborts loudly if not.

Bookkeeping: every reference is keyed by the full POTCAR identity
(TITEL + sha256), never by bare element symbol.

Usage: edit the CONFIG block below, then  `python free_atom_refs.py`
"""

import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path

# ------------------------- CONFIG (env-driven) --------------------------
# POTCAR_DIR (required): exported by the submission script; the directory
# CONTAINING POT_GGA_PAW_PBE/ (legacy MP PBE library).
# VASP_CMD   (optional): exported by the submission script; falls back to
# a plain mpirun for interactive use.
POTCAR_DIR = os.environ.get("POTCAR_DIR")
if not POTCAR_DIR:
    sys.exit(
        "error: POTCAR_DIR is not set. Export it before running, e.g.\n"
        "  export POTCAR_DIR=/path/to/pseudos"
    )
if not Path(POTCAR_DIR).is_dir():
    sys.exit(f"error: POTCAR_DIR does not exist: {POTCAR_DIR}")

VASP_CMD = os.environ.get("VASP_CMD", "mpirun -np 4 vasp_std")

WORKDIR = os.environ.get("FREE_ATOM_WORKDIR", "free_atom_refs")  # output directory
ELEMENTS = os.environ.get("FREE_ATOM_ELEMENTS", "").split() or None
# None -> every element MP has a POTCAR for; or e.g. "Fe O" via the env var.
# Per-element POTCAR variant override, e.g. '{"Mo": "Mo_sv"}' for datasets not
# using MP's preferred variant (CJLM MoS2). Passed to MPStaticSet's
# user_potcar_settings. Use a separate FREE_ATOM_WORKDIR so the run does not
# collide with the MP-variant reference for the same element.
POTCAR_VARIANTS = json.loads(os.environ.get("FREE_ATOM_POTCAR_VARIANTS", "{}"))
# POTCAR library to draw from, e.g. "PBE_54" -> POT_GGA_PAW_PBE_54/. None ->
# MPStaticSet's default ("PBE" -> POT_GGA_PAW_PBE/, the legacy MP library).
# Needed for Mo_sv: the legacy library only carries Mo and Mo_pv.
POTCAR_FUNCTIONAL = os.environ.get("FREE_ATOM_POTCAR_FUNCTIONAL") or None
BOX = (13.0, 14.0, 15.0)  # Angstrom, deliberately unequal
DRY_RUN = False  # True: write inputs, skip VASP
# ------------------------------------------------------------------------

# pymatgen reads PMG_VASP_PSP_DIR at import time -> set it before importing
os.environ["PMG_VASP_PSP_DIR"] = POTCAR_DIR

from pymatgen.core import Lattice, Structure  # noqa: E402
from pymatgen.io.vasp.inputs import Incar, Kpoints  # noqa: E402
from pymatgen.io.vasp.sets import MPRelaxSet, MPStaticSet  # noqa: E402

# INCAR overrides turning an MP static run into a frozen-occupancy reference.
NONSCF_OVERRIDES = {
    "ICHARG": 12,  # fixed atomic-superposition density, not updated
    "NELM": 1,  # one diagonalization, occupancies stay at initialization
    "ISYM": 0,
    "ISMEAR": 0,
    "SIGMA": 0.01,
    "NSW": 0,
    "LCHARG": True,
    "LAECHG": False,
    "LVHAR": False,
    "LORBIT": None,  # None -> remove key
    "LREAL": False,
    "EDIFF": 1e-5,
    "ALGO": "Normal",
}

# MP's +U values (LDAUTYPE=2, applied to these d-elements with O/F anions).
# Used only to VERIFY the installed MPStaticSet; the authoritative source
# remains the pymatgen config.
MP_LDAUU_O = {
    "Co": 3.32,
    "Cr": 3.7,
    "Fe": 5.3,
    "Mn": 3.9,
    "Mo": 4.38,
    "Ni": 6.2,
    "V": 3.25,
    "W": 6.2,
}


def mp_config():
    return MPRelaxSet.CONFIG  # MPStaticSet inherits MPRelaxSet's config


def verify_mp_ldau_convention():
    """Abort unless MPStaticSet reproduces MP's exact DFT+U treatment."""
    inc_cfg = mp_config()["INCAR"]

    # 1) static config: type-2 (Dudarev), MP U values keyed by O anion
    assert inc_cfg.get("LDAUTYPE", 2) == 2, "LDAUTYPE != 2 (Dudarev)"
    ldauu_o = inc_cfg["LDAUU"]["O"]
    ldaul_o = inc_cfg["LDAUL"]["O"]
    for el, u in MP_LDAUU_O.items():
        assert abs(ldauu_o[el] - u) < 1e-6, f"U({el}) = {ldauu_o[el]} != {u}"
        assert ldaul_o[el] == 2, f"LDAUL({el}) != 2"
    assert "F" in inc_cfg["LDAUU"], "F-anion U trigger missing"

    # 2) functional check: Fe with O anion -> LDAU on, U(Fe)=5.3, LDAUL=2
    s = Structure(Lattice.cubic(4.3), ["Fe", "O"], [[0, 0, 0], [0.5, 0.5, 0.5]])
    inc = MPStaticSet(s).incar
    assert inc.get("LDAU") is True, "Fe-O did not trigger LDAU"
    ife = [sp.symbol for sp in s.composition].index("Fe")
    assert abs(inc["LDAUU"][ife] - 5.3) < 1e-6
    assert inc["LDAUL"][ife] == 2
    assert inc.get("LDAUTYPE") == 2

    # 3) functional check: a lone atom must NOT trigger LDAU
    s1 = Structure(Lattice.orthorhombic(*BOX), ["Fe"], [[0.5, 0.5, 0.5]])
    inc1 = MPStaticSet(s1).incar
    assert not inc1.get("LDAU", False), "lone atom unexpectedly has LDAU on"

    print(
        "[ok] MPStaticSet reproduces the MP DFT+U treatment "
        "(LDAUTYPE=2, MP U values, O/F anion trigger, no U for lone atoms)"
    )


def mp_lmaxmix_for(el: str):
    """LMAXMIX that MP convention would use for `el` in a U-active calc,
    per the rule: 6 if any LDAUL channel is l=3, else 4 if any is l=2,
    else None (element never gets U in MP -> no ldau_convention variant)."""
    ls = set()
    for anion_map in mp_config()["INCAR"]["LDAUL"].values():
        if el in anion_map:
            ls.add(anion_map[el])
    if 3 in ls:
        return 6
    if 2 in ls:
        return 4
    return None


def element_list():
    if ELEMENTS is not None:
        return list(ELEMENTS)
    return sorted(mp_config()["POTCAR"].keys())


def potcar_identity(path: Path):
    text = path.read_bytes()
    titel = [
        ln.strip() for ln in text.decode(errors="ignore").splitlines() if "TITEL" in ln
    ]
    return {"titel": titel, "sha256": hashlib.sha256(text).hexdigest()}


def write_inputs(el: str, folder: Path, lmaxmix=None):
    s = Structure(Lattice.orthorhombic(*BOX), [el], [[0.5, 0.5, 0.5]])
    vis = MPStaticSet(
        s,
        user_incar_settings=NONSCF_OVERRIDES,
        user_kpoints_settings=Kpoints.gamma_automatic((1, 1, 1)),
        user_potcar_settings=POTCAR_VARIANTS or None,
        user_potcar_functional=POTCAR_FUNCTIONAL,
    )
    vis.write_input(str(folder))
    if lmaxmix is not None:  # post-process, mirroring the MP/Koker convention
        inc = Incar.from_file(folder / "INCAR")
        inc["LMAXMIX"] = lmaxmix
        inc.write_file(folder / "INCAR")


def run_vasp(folder: Path):
    with open(folder / "vasp.out", "w") as out:
        subprocess.run(
            VASP_CMD,
            shell=True,
            cwd=folder,
            stdout=out,
            stderr=subprocess.STDOUT,
            check=True,
        )
    chg = folder / "CHGCAR"
    assert chg.exists() and "augmentation occupancies" in chg.read_text(), (
        f"{folder}: CHGCAR missing augmentation occupancies"
    )


def main():
    verify_mp_ldau_convention()
    root = Path(WORKDIR)
    root.mkdir(exist_ok=True)
    manifest = {}

    for el in element_list():
        variants = {"plain": None}
        lmm = mp_lmaxmix_for(el)
        if lmm is not None:
            variants["ldau_convention"] = lmm

        for name, lmaxmix in variants.items():
            folder = root / el / name
            if (folder / "CHGCAR").exists():
                print(f"[skip] {el}/{name} (CHGCAR exists)")
                continue
            folder.mkdir(parents=True, exist_ok=True)
            try:
                write_inputs(el, folder, lmaxmix=lmaxmix)
            except Exception as e:  # e.g. POTCAR not in local library
                print(f"[warn] {el}/{name}: could not write inputs: {e}")
                continue
            if not DRY_RUN:
                print(
                    f"[run ] {el}/{name}" + (f" (LMAXMIX={lmaxmix})" if lmaxmix else "")
                )
                try:
                    run_vasp(folder)
                except Exception as e:
                    print(f"[fail] {el}/{name}: {e}")
                    continue
            manifest.setdefault(el, {})[name] = {
                "path": str(folder),
                "lmaxmix": lmaxmix,
                "potcar": potcar_identity(folder / "POTCAR"),
            }

    (root / "manifest.json").write_text(json.dumps(manifest, indent=2))
    print(f"[done] manifest -> {root / 'manifest.json'}")


if __name__ == "__main__":
    sys.exit(main())
